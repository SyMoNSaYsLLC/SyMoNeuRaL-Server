"""#81: `/livestack/<name>` for every application, and the page split into html + js + css.

R-154: *"the https://symoneural.com/image.html needs to be updated to
https://symoneural.com/livestack/image and the image html should be static with json and
css"*, corrected one minute later -- *"**correction not json it was suppose to be js**"* --
then scoped: *"apply this to all applications."*

Three separate things have to hold at once for that to be true of a visitor, and each of
them has failed on its own somewhere in this repo's history:

  1. **The clean address answers.** Guarded here and, through Caddy, by
     `apps/test_caddy_delegation.py` -- a route can answer perfectly on 127.0.0.1:8800 and
     404 at the public address, which has happened six times.
  2. **The old address still answers.** #81 is explicit that the clean URLs "are an
     addition, not a redirect". `/image.html` is published and shared, and a 404 on a link
     that used to work is the one failure this site cannot afford.
  3. **The split actually happened, in the generator.** `site/image.html` is GENERATED by
     `tools/build_pages.py`. A hand-written `site/image.js` beside a generated page is a
     second source of truth for one surface, and the next generator run would revert half
     of it and keep the other half.

## What this file deliberately does not claim

Every assertion below reads the disk. None of them can tell you the page WORKS -- that a
deferred external script still finds `$` and `status()`, that the render handler is still
bound, that anything is drawn. `.claude/CLAUDE.md` says it plainly: *"If the deliverable is
a program that runs, one check must be something only a real run can turn green."* #94
shipped eighteen green checks over a chat surface that was dead on arrival.

So the run-only check for this task is in `tests/frontend.mjs` -- it loads `/livestack/image`
in a real browser, asserts the page's own script executed by reading a value only that
script sets, and asserts the same document answers at `/image.html`. That is the assertion
that cannot be satisfied by a file existing. This file is the cheap half.

Nothing here imports `api.py` -- it is the serving module, and importing it builds every
rate limiter, resolves the GPU governor and mounts `site/`. It is read as text, the same way
`test_deploy_routes.py` and `test_caddy_delegation.py` read it.
"""
from __future__ import annotations

import ast
import importlib.util
import pathlib
import re
import unittest

REPO = pathlib.Path(__file__).resolve().parents[2]
API = REPO / "backend" / "api.py"
SITE = REPO / "site"
GENERATOR = REPO / "tools" / "build_pages.py"


def _livestack_pages() -> dict[str, str]:
    """`LIVESTACK_PAGES` read out of `api.py` as text: {name: filename}.

    Whole-line `#` comments are dropped first, for the reason `test_caddy_delegation.py`
    documents at length -- a comment that merely NAMED a declaration form once produced a
    page path that no route serves and no Caddy block ever would.
    """
    src = "\n".join(
        "" if line.lstrip().startswith("#") else line
        for line in API.read_text().splitlines()
    )
    for node in ast.walk(ast.parse(src)):
        if not isinstance(node, ast.Assign):
            continue
        if any(isinstance(t, ast.Name) and t.id == "LIVESTACK_PAGES" for t in node.targets):
            return {k.value: v.value for k, v in zip(node.value.keys, node.value.values)}
    return {}


def _generator():
    """Import `tools/build_pages.py` without running it.

    It is not on the path and not a package; `main()` is behind an `if __name__` guard, so
    importing is side-effect free and writes nothing. Importing rather than re-parsing is
    the point of the round-trip assertion below: it compares the file on disk against the
    string the generator would emit, which is the only comparison that catches a hand-edit.
    """
    spec = importlib.util.spec_from_file_location("_build_pages", GENERATOR)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


class LivestackRouteTests(unittest.TestCase):

    def test_the_extraction_found_something_to_test(self):
        """The vacuity guard. Every assertion below iterates LIVESTACK_PAGES, so all of them
        pass trivially against an empty dict -- and this repo has already retired checks that
        scored green on an empty file."""
        pages = _livestack_pages()
        self.assertTrue(pages, "LIVESTACK_PAGES not found in backend/api.py, or empty")
        self.assertIn("image", pages, "image is the page #81 says to do first and all the "
                                      "way through before repeating the pattern")

    def test_both_spellings_are_registered_for_every_page(self):
        """The pair cannot be allowed to drift, which is the entire reason this is a dict.

        Asserted against the registration LOOP rather than against a list of decorators: if
        somebody replaces the loop with literals, one spelling will eventually be typed and
        the other forgotten, and the failure is silent -- a missing decorator is not a broken
        one and nothing goes red."""
        src = API.read_text()
        self.assertRegex(
            src, r'app\.get\(\s*f"/livestack/\{_name\}"',
            "the /livestack/<name> registration is gone from api.py")
        self.assertRegex(
            src, r'app\.get\(\s*f"/live-stack/\{_name\}"',
            "the hyphenated spelling is gone -- /live-stack/<name> is the address Garrett "
            "typed (R-160) and it must keep answering")

    def test_no_livestack_page_is_served_as_a_redirect(self):
        """#81: the clean URLs "are an addition, not a redirect", and this is not cosmetic.

        `/livestack/live`'s docstring in api.py records the specific cost: a redirect breaks
        a `<video>` mid-playlist, because the player resolves segment URIs relative to the
        manifest it was handed. The general cost is that the address in the operator's URL
        bar stops agreeing with the address they typed."""
        src = API.read_text()
        body = src[src.index("LIVESTACK_PAGES = {"):]
        body = body[:body.index("# ---- /local")]
        for bad in ("RedirectResponse", "status_code=301", "status_code=302"):
            self.assertNotIn(bad, body,
                             f"{bad} appears in the LIVESTACK_PAGES block -- these routes "
                             "serve the page, they do not redirect to it")

    def test_the_old_html_address_still_exists(self):
        """Requirement 2. The clean URL is an addition; `/image.html` is published and shared.

        The file being present in `site/` is what makes the old address answer: `api.py`
        mounts `site/` at `/` below every route, so the page keeps answering at its own name
        for everything that already links it. Delete the file to "finish the migration" and
        every one of those links 404s."""
        for name, filename in _livestack_pages().items():
            with self.subTest(name=name):
                self.assertTrue((SITE / filename).is_file(),
                                f"site/{filename} is gone, so /{filename} now 404s for "
                                "every link and bookmark that already points at it")

    def test_every_page_is_split_into_html_js_and_css(self):
        """Requirement 3, the half a route test would otherwise skip entirely.

        *"the image html should be static with [js] and css"*. Asserted as three files AND
        as three references, because either alone is satisfiable without the other: the
        files can exist unreferenced, and the references can point at nothing."""
        for name, filename in _livestack_pages().items():
            with self.subTest(name=name):
                stem = filename[:-len(".html")]
                html = (SITE / filename).read_text()
                for asset in (f"{stem}.js", f"{stem}.css"):
                    self.assertTrue((SITE / asset).is_file(), f"site/{asset} is missing")
                    self.assertIn(f'/{asset}', html,
                                  f"site/{filename} does not reference /{asset}")

    def test_the_page_behaviour_is_not_also_still_inline(self):
        """A split that leaves the old inline copy behind is worse than no split.

        Two copies of one handler is the drift `.claude/CLAUDE.md` bans second state
        documents to prevent, and here it would bind every listener twice -- one submit
        producing two renders, which on this box means two GPU leases queued behind each
        other for one click.

        `<script src=...>` tags are stripped before the check so the assertion is about
        INLINE code only, and the shell's shared `$`/`status()`/`api()` block is expected to
        remain inline: it runs at parse time, which is what lets the deferred page script
        find those three defined."""
        for name, filename in _livestack_pages().items():
            with self.subTest(name=name):
                stem = filename[:-len(".html")]
                html = (SITE / filename).read_text()
                inline = "\n".join(
                    m.group(1) for m in
                    re.finditer(r"<script(?![^>]*\ssrc=)[^>]*>(.*?)</script>", html, re.S))
                page_js = (SITE / f"{stem}.js").read_text()
                # The handler that owns the surface. If its first line is in both files,
                # both copies run.
                signature = "form.addEventListener"
                self.assertIn(signature, page_js,
                              f"site/{stem}.js does not carry the page's submit handler -- "
                              "the split moved the reference but not the behaviour")
                self.assertNotIn(signature, inline,
                                 f"site/{filename} still carries the submit handler inline "
                                 f"as well as in /{stem}.js; every listener binds twice")

    def test_the_split_files_are_written_by_the_generator_not_by_hand(self):
        """The one that catches the repair somebody makes at 2am and loses at 2:05.

        `site/image.html` is generated. So are `site/image.js` and `site/image.css` -- and
        because the generator overwrites them without asking, a hand-edit to either survives
        exactly until the next `python3 tools/build_pages.py` and then vanishes with no
        error, no conflict and no line in `git status` to explain it.

        Compared byte-for-byte against the string the generator holds, not by looking for the
        banner comment: a banner is copied along with the rest of the file by whoever pastes
        over it, so it proves the file was generated ONCE and says nothing about now."""
        gen = _generator()
        for name, filename in _livestack_pages().items():
            with self.subTest(name=name):
                stem = filename[:-len(".html")]
                for asset, attr in ((f"{stem}.js", f"{name.upper()}_JS"),
                                    (f"{stem}.css", f"{name.upper()}_CSS")):
                    self.assertTrue(hasattr(gen, attr),
                                    f"tools/build_pages.py has no {attr}, so site/{asset} "
                                    "is not generated and nothing regenerates it")
                    self.assertEqual(
                        (SITE / asset).read_text(), getattr(gen, attr),
                        f"site/{asset} differs from tools/build_pages.py's {attr}. Either it "
                        "was hand-edited -- the next generator run will silently revert it "
                        "-- or the generator was changed without re-running it, and the "
                        "deployed page is stale. Run python3 tools/build_pages.py, then "
                        "python3 tools/build_cachebust.py.")

    def test_the_generated_head_carries_no_unsubstituted_placeholder(self):
        """An unsubstituted placeholder is not a blank -- it ships as literal text.

        The page-css link was a `@@PAGECSS@@` SHELL placeholder for one day, and the 0.5
        re-measure retired it: `build_exp.py` and Studio's builder import the shared SHELL
        with their own field dicts, and a placeholder they do not know is a red vacuity
        guard on a correct page. It is an insertion in `page()` now. This test stays,
        checking ALL of `site/` for any `@@KEY@@` that escaped substitution, because the
        shell's placeholders are a contract with every generator that imports it."""
        for f in sorted(SITE.glob("*.html")):
            with self.subTest(page=f.name):
                self.assertNotRegex(f.read_text(), r"@@[A-Z_]+@@",
                                    "an unsubstituted generator placeholder is in this page")


if __name__ == "__main__":
    unittest.main()
