"""Tools that understand *this* stack specifically.

`fs.py` and `host.py` would let a model work all of the below out by reading files and running
commands, and it would take a dozen turns and a great deal of context to do it. These tools
encode what the repo's own conventions already fix, so the agent starts from knowledge rather
than from archaeology:

- an app is a package under `backend/apps/<name>/` exporting `router` from `__init__.py`
- `backend/api.py` is the only module that mounts routers, and it does so before the static
  mount at `/`
- most surfaces are off unless their `SYMONEURAL_<NAME>_ENABLED` / `SYMONEURAL_<NAME>_TOKEN` pair is set
- pages are generated by `tools/build_*.py` into `site/`, never edited there

`list_routes` parses `api.py` with `ast` rather than importing it. Importing that module
builds a FastAPI app, reads the registry and touches the governor -- side effects that have no
business happening because somebody asked what routes exist. `apps/test_studio_models.py`
takes the same approach for the same reason, and this follows it deliberately.
"""
from __future__ import annotations

import ast
import json
import os
import pathlib
import re

from .. import workspace
from ..registry import tool


def _apps_dir() -> pathlib.Path | None:
    return workspace.APPS if workspace.APPS and workspace.APPS.is_dir() else None


def _env_names(d: pathlib.Path) -> set[str]:
    """Every SYMONEURAL_* name the package mentions. A regex over source rather than an import,
    because these are read through `os.environ.get` with a string literal in every case in
    this repo, and because importing an app to find out what it configures is backwards."""
    names: set[str] = set()
    for f in d.rglob("*.py"):
        if ".venv" in f.parts or "__pycache__" in f.parts:
            continue
        try:
            names |= set(re.findall(r"\bSYMONEURAL_[A-Z0-9_]+",
                                    f.read_text(encoding="utf-8", errors="replace")))
        except OSError:
            continue
    return names


@tool("stack")
def list_apps() -> dict:
    """List the application packages in the live stack and whether each is switched on.

    An app is a directory under backend/apps/ with an __init__.py. `enabled` reflects the
    SYMONEURAL_<NAME>_ENABLED switch that gates most surfaces; null means the package does not use
    that pattern, which is not the same as being off.
    """
    apps = _apps_dir()
    if apps is None:
        return {"error": "no_apps_dir", "root": str(workspace.ROOT)}
    rows = []
    for d in sorted(apps.iterdir()):
        if not d.is_dir() or d.name.startswith(("_", ".")):
            continue
        init = d / "__init__.py"
        if not init.is_file():
            continue
        src = init.read_text(encoding="utf-8", errors="replace")
        gate = f"SYMONEURAL_{d.name.upper()}_ENABLED"
        gated = gate in src
        rows.append({
            "name": d.name,
            "path": str(d),
            "has_router": "router" in src,
            "has_page": (d / "page.html").is_file(),
            "has_venv": (d / ".venv").is_dir(),
            "gate_env": gate if gated else None,
            "enabled": (os.environ.get(gate) == "1") if gated else None,
            "files": sorted(f.name for f in d.iterdir() if f.is_file()),
        })
    return {"apps_dir": str(apps), "count": len(rows), "apps": rows}


@tool("stack")
def list_routes(include_static: bool = False) -> dict:
    """List every HTTP route backend/api.py declares, read from source without importing it.

    Args:
        include_static: Also report the StaticFiles mount, which matches everything and so
            must come after every route above it.
    """
    root = workspace.ROOT
    if root is None:
        return {"error": "no_root"}
    api = root / "backend" / "api.py"
    if not api.is_file():
        return {"error": "no_api_py", "expected": str(api)}
    try:
        tree = ast.parse(api.read_text(encoding="utf-8"), filename=str(api))
    except SyntaxError as e:
        return {"error": "unparseable_api_py", "detail": str(e)}

    routes: list[dict] = []
    routers: list[dict] = []
    mounts: list[dict] = []
    verbs = {"get", "post", "put", "patch", "delete", "head", "options", "websocket"}

    for node in ast.walk(tree):
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
            continue
        attr = node.func.attr
        first = node.args[0] if node.args else None
        literal = first.value if isinstance(first, ast.Constant) else None
        if attr in verbs and isinstance(literal, str):
            routes.append({"method": attr.upper(), "path": literal, "line": node.lineno})
        elif attr == "include_router":
            prefix = next((kw.value.value for kw in node.keywords
                           if kw.arg == "prefix" and isinstance(kw.value, ast.Constant)), None)
            routers.append({"router": ast.unparse(node.args[0]) if node.args else "?",
                            "prefix": prefix, "line": node.lineno})
        elif attr == "mount" and isinstance(literal, str):
            mounts.append({"path": literal, "line": node.lineno})

    out: dict = {"api_py": str(api),
                 "routes": sorted(routes, key=lambda r: r["line"]),
                 "route_count": len(routes),
                 "routers": sorted(routers, key=lambda r: r["line"]),
                 "router_count": len(routers)}
    if include_static:
        out["mounts"] = mounts
        out["note"] = ("StaticFiles at / matches everything, so every route must be declared "
                       "before the mount line to be reachable at all.")
    return out


@tool("stack")
def app_status(name: str) -> dict:
    """Call an app package's own status() and report what it says about itself.

    This is the honest answer to "is X working": each package computes its state from the disk
    and the process table rather than from a constant.

    Args:
        name: The app package name, e.g. "voice" or "sigils".
    """
    apps = _apps_dir()
    if apps is None:
        return {"error": "no_apps_dir"}
    if not (apps / name / "__init__.py").is_file():
        return {"error": "no_such_app", "name": name}
    import importlib
    import sys
    if str(apps) not in sys.path:
        sys.path.insert(0, str(apps))
    try:
        mod = importlib.import_module(name)
    except Exception as e:
        # Several packages import from their own venv and cannot be imported by the serving
        # interpreter at all. That is a real answer about the app, not a failure of this tool.
        return {"error": "import_failed", "name": name, "detail": f"{type(e).__name__}: {e}"}
    out: dict = {"name": name}
    for fn in ("status", "enabled", "installed"):
        f = getattr(mod, fn, None)
        if callable(f):
            try:
                out[fn] = f()
            except Exception as e:
                out[fn] = {"error": f"{type(e).__name__}: {e}"}
    return out


@tool("stack")
def read_app_config(name: str) -> dict:
    """Read an app package's documentation and configuration surface.

    Returns the __init__.py docstring -- which in this repo is where each app's contract with
    api.py is written down -- the environment switches it reads, and its file list.

    Args:
        name: The app package name.
    """
    apps = _apps_dir()
    if apps is None:
        return {"error": "no_apps_dir"}
    d = apps / name
    init = d / "__init__.py"
    if not init.is_file():
        return {"error": "no_such_app", "name": name}
    src = init.read_text(encoding="utf-8", errors="replace")
    try:
        doc = ast.get_docstring(ast.parse(src)) or ""
    except SyntaxError as e:
        doc = f"<unparseable: {e}>"
    envs = sorted(_env_names(d))
    return {"name": name, "path": str(d), "docstring": doc,
            "env_vars": {n: (os.environ.get(n) is not None) for n in envs},
            "files": sorted(str(f.relative_to(d)) for f in d.rglob("*")
                            if f.is_file() and ".venv" not in f.parts
                            and "__pycache__" not in f.parts)[:200]}


@tool("stack")
def list_models() -> dict:
    """The model inventory, read from run/registry.json.

    This is the pre-computed list tools/build_registry.py writes out-of-band. It is read
    rather than scanned on purpose: walking the HF cache and parsing GGUF headers is a
    control-plane job that has to stay off the live request path.
    """
    run = workspace.RUN
    if run is None:
        return {"error": "no_root"}
    f = run / "registry.json"
    if not f.is_file():
        return {"error": "no_registry", "expected": str(f),
                "detail": "run python3 tools/build_registry.py to produce it"}
    try:
        doc = json.loads(f.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        return {"error": "unreadable_registry", "path": str(f), "detail": str(e)}
    models = doc.get("models") if isinstance(doc, dict) else None
    return {"source": str(f), "count": len(models) if isinstance(models, list) else 0,
            "models": models if isinstance(models, list) else []}


@tool("stack")
def list_generators() -> dict:
    """List the tools/build_*.py static-site generators and what each one writes.

    Pages in site/ are generated, never hand-edited -- editing site/ directly means the next
    deploy silently reverts the change. build_cachebust.py must run last.
    """
    root = workspace.ROOT
    if root is None:
        return {"error": "no_root"}
    tdir = root / "tools"
    if not tdir.is_dir():
        return {"error": "no_tools_dir", "expected": str(tdir)}
    rows = []
    for f in sorted(tdir.glob("build_*.py")):
        src = f.read_text(encoding="utf-8", errors="replace")
        try:
            doc = (ast.get_docstring(ast.parse(src)) or "").split("\n\n")[0].strip()
        except SyntaxError:
            doc = ""
        rows.append({"generator": f.name, "path": str(f), "summary": doc,
                     "must_run_last": f.name == "build_cachebust.py"})
    return {"tools_dir": str(tdir), "count": len(rows), "generators": rows}
