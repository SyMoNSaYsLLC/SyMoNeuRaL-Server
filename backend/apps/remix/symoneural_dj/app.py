from .symon_client import SymonClient

# Open without an account: the UI shell, health, the account login/signup
# pages, and Spotify's OAuth redirect back (it carries the session cookie +
# Spotify's own state, not a bearer). Everything else needs a real identity.
_OPEN_PATHS = {"/", "/health", "/auth/login", "/auth/signup", "/spotify/callback"}

_INDEX_HTML = Path(__file__).resolve().parent.parent / "static" / "index.html"


class PlaylistRequest(BaseModel):
    prompt: str = Field(min_length=1, max_length=2000)
    # Capped like every other free-text field. `user` is a Spotify account id
    # that must already be in the token store, and `name` becomes the created
    # playlist's title — both were unbounded, so a caller could push an
    # arbitrarily large string through validation and into an outbound API call
    # or an error message. Bounded 2026-08-10.
    user: str = Field(min_length=1, max_length=128)
    track_count: int = Field(default=30, ge=5, le=100)
    name: str | None = Field(default=None, max_length=200)
    public: bool = False
    use_taste_profile: bool = True
    # Blend: fold these users' taste profiles in too. The playlist is still
    # created on `user`'s account; every id here must be in the token store.
    blend_with: list[str] = Field(default_factory=list, max_length=10)


def _is_loopback(host: str) -> bool:
    try:
        return ipaddress.ip_address(host).is_loopback
    except ValueError:
        return False


def create_app(
    settings: Settings | None = None,
    spotify: SpotifyClient | None = None,
    symon: SymonClient | None = None,
) -> FastAPI:
    settings = settings or load_settings()
    store = TokenStore(settings.token_path)
    owners = OwnershipStore(settings.token_path.parent / "spotify_owners.json")
    # The shared accounts+billing module — DJ_TOKEN is the break-glass owner.
    accounts = AccountsModule(settings.accounts_db, owner_env_token=settings.dj_token)
    router = build_router(accounts, secure_cookies=settings.secure_cookies, app_name="DJ")
    # Data pump: every successful playlist banks a commercial-clean training
    # pair into the shared distill store (symon learns from normal use).
    captures = CaptureStore(settings.capture_dir)

    def _capture(messages, verdict, meta):
        # No source is recorded: provenance.py was deleted 2026-08-11. Playlists
        # are generated by the local symon today, so captured turns are its own
        # output — but that is now a property of the code rather than something
        # the written record asserts.
        captures.capture("dj", messages, verdict=verdict, meta=meta)
    if spotify is None:
        spotify = SpotifyClient(
            settings.spotify_client_id,
            settings.spotify_client_secret,
            settings.spotify_redirect_uri,
            store,
        )
    if symon is None:
        symon = SymonClient(settings.symon_url, settings.vllm_api_key)
    jobs = JobStore()
    # Terminal states live next to the token store, so polling a finished job
    # keeps working across restarts.
    journal = JobJournal(settings.token_path.parent / "jobs.jsonl")

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        yield
        await spotify.aclose()
        await symon.aclose()

    app = FastAPI(title="symoneural_dj", version="0.1.0", lifespan=lifespan)
    app.state.jobs = jobs
    app.state.token_store = store
    app.state.accounts = accounts
    app.state.spotify_owners = owners
    app.include_router(router)  # /auth/*, /account/*, owner /admin/*

    def _identify(request: Request):
        auth = request.headers.get("authorization", "")
        bearer = auth[7:] if auth.startswith("Bearer ") else ""
        return accounts.identify(cookie=request.cookies.get(accounts.cookie_name(), ""),
                                 bearer=bearer)

    @app.middleware("http")
    async def _auth(request: Request, call_next):
        path = request.url.path
        # Router-owned auth pages/actions authenticate themselves.
        if path in _OPEN_PATHS or path.startswith("/auth/") or path.startswith("/account/") \
                or path.startswith("/admin/"):
            return await call_next(request)
        ident = _identify(request)
        if ident is None:
            # No identity. Fail closed — but preserve the loopback-only dev
            # path when nothing is configured at all (no owner token, no users).
            if not settings.dj_token and not accounts.accounts.listing():
                peer = request.client.host if request.client else ""
                if _is_loopback(peer):
                    request.state.identity = accounts.owner_identity()  # trusted local dev
                    return await call_next(request)
            return JSONResponse({"error": "login required"}, status_code=401)
        request.state.identity = ident
        return await call_next(request)

    @app.get("/")
    async def index():
        return FileResponse(_INDEX_HTML, media_type="text/html")

    @app.get("/health")
    async def health():
        """Liveness for the family gateway, which colours the DJ tile from this.

        Returns the house shape ({ok, app, port}) rather than the bare `{}` it
        returned until 2026-08-10. An empty body is a 200 that says nothing: it
        cannot tell you WHICH service answered, so a misrouted proxy or a port
        collision reads as healthy. symoneural_tune, symoneural_tensor and
        Studio already answered this way; DJ, chat, image, the gateway and the
        engine did not.

        Deliberately cheap and unauthenticated, matching the family: no account
        lookup, no Spotify call, no disk read. It answers "this process is
        accepting requests" and nothing more, so a dead upstream can never make
        the process look dead.
        """
        return {"ok": True, "app": "symoneural_dj", "port": settings.port}

    @app.get("/spotify/connect")
    async def spotify_connect(request: Request):
        # Must be a logged-in account to connect a Spotify profile to it.
        if getattr(request.state, "identity", None) is None:
            return JSONResponse({"error": "login required"}, status_code=401)
        try:
            return RedirectResponse(spotify.authorize_url())
        except SpotifyAuthError as exc:
            return JSONResponse({"error": str(exc)}, status_code=500)

    @app.get("/spotify/callback")
    async def spotify_callback(request: Request):
        # Browser redirect: identity rides the session cookie, not a bearer.
        ident = _identify(request)
        if ident is None:
            return JSONResponse({"error": "log in, then reconnect Spotify"}, status_code=401)
        if request.query_params.get("error"):
            return JSONResponse(
                {"error": f"spotify refused: {request.query_params['error']}"},
                status_code=400)
        code = request.query_params.get("code")
        state = request.query_params.get("state", "")
        if not code or not spotify.consume_state(state):
            return JSONResponse(
                {"error": "missing code or unknown/expired state"}, status_code=400)
        try:
            who = await spotify.handle_callback(code)
        except SpotifyAuthError as exc:
            return JSONResponse({"error": str(exc)}, status_code=500)
        owners.claim(ident.user_id, who["user"])  # this account now owns it
        return {"authorized": who["user"], "display_name": who["display_name"],
                "next": "GET /users, then POST /playlist with that user id"}

    def _visible_users(request: Request) -> list[str]:
        """Owner sees every stored Spotify connection; a member sees only the
        ones their account has connected — the cross-tenant boundary."""
        ident = request.state.identity
        if ident.is_owner:
            return [u["user"] for u in store.users()]
        return owners.owned_by(ident.user_id)

    @app.get("/users")
    async def users(request: Request):
        allowed = set(_visible_users(request))
        return {"users": [u for u in store.users() if u["user"] in allowed]}

    @app.post("/playlist")
    async def create_playlist(request: Request, body: PlaylistRequest):
        ident = request.state.identity
        requested = dict.fromkeys([body.user, *body.blend_with])
        unknown = [u for u in requested if store.get_user(u) is None]
        if unknown:
            return JSONResponse(
                {"error": f"unknown user(s) {unknown} — connect via /spotify/connect",
                 "known_users": _visible_users(request)},
                status_code=404)
        # Cross-tenant boundary: a member may only use Spotify accounts THEY
        # connected. The owner may act on any. This is the security fix.
        if not ident.is_owner:
            forbidden = [u for u in requested if not owners.owns(ident.user_id, u)]
            if forbidden:
                return JSONResponse(
                    {"error": f"not your Spotify account(s): {forbidden}"},
                    status_code=403)
        # Money: hold the per-playlist cost up front (owner free). Settled on
        # success, refunded on failure — inside run_job.
        try:
            hold_id = accounts.meter.hold(
                ident.user_id, ident.user.role, "playlist", settings.playlist_cost)
        except InsufficientFunds as exc:
            return JSONResponse({"error": str(exc)}, status_code=402)  # Payment Required
        job = jobs.create(
            user=body.user, prompt=body.prompt, track_count=body.track_count,
            name=body.name, public=body.public,
            use_taste_profile=body.use_taste_profile,
            blend_with=[u for u in dict.fromkeys(body.blend_with) if u != body.user],
        )
        job.task = asyncio.create_task(
            run_job(job, spotify, symon, journal, accounts.meter, hold_id, _capture))
        return {"job_id": job.id}

    @app.get("/playlist/{job_id}")
    async def get_playlist_job(job_id: str, request: Request):
        allowed = set(_visible_users(request))
        job = jobs.get(job_id)
        if job is not None:
            record = job.as_dict()
        else:
            # Restart survivor: finished jobs answer from the journal.
            record = journal.lookup(job_id)
        # 404 rather than 403 for someone else's job: a 403 confirms the id
        # exists, which makes job ids enumerable. The caller cannot tell an
        # unknown id from one they may not see, which is the point.
        if record is None or record.get("user") not in allowed:
            return JSONResponse({"error": "no such job"}, status_code=404)
        return record

    @app.get("/jobs")
    async def list_jobs(request: Request):
        """Last 20 jobs, newest first: live ones from memory, finished ones
        from the journal (which survives restarts).

        Filtered by the same cross-tenant boundary as /users and /playlist.
        Until 2026-08-10 it was not: every record carries `prompt`, and finished
        ones carry the playlist URL and what the user was charged, so any member
        could read every other member's prompts and results by calling this. The
        boundary existed and this route simply did not ask for it.
        """
        allowed = set(_visible_users(request))
        seen: set[str] = set()
        out: list[dict] = []
        live = sorted(jobs.all(), key=lambda j: j.id)  # stable; live set is small
        for job in live:
            if job.state not in TERMINAL_STATES and job.user in allowed:
                record = job.as_dict()
                record["prompt"] = job.prompt
                out.append(record)
                seen.add(job.id)
        for record in journal.recent(20):
            if record["job_id"] not in seen and record.get("user") in allowed:
                out.append(record)
                seen.add(record["job_id"])
        return {"jobs": out[:20]}

    return app
