"""The FastAPI app the phone talks to.

Auth is ONE middleware over every path with a set allowlist — deliberately
the same shape as symon_llm's gateway, because its per-route version shipped
a hole (/metrics went out without the check). /health stays open for
dashboards; /auth/login and /auth/callback are browser-driven and carry
Spotify's own state CSRF check instead of the bearer.

With DJ_TOKEN unset the app serves loopback peers only — the same fail-safe
shape as the engine with VLLM_API_KEY unset.
"""
from __future__ import annotations

import asyncio
import ipaddress
from contextlib import asynccontextmanager

from pathlib import Path

from fastapi import FastAPI, Request
from fastapi.responses import FileResponse, JSONResponse, RedirectResponse
from pydantic import BaseModel, Field

# These two were `symon_capture` and `symoneural_accounts`: editable installs whose finders
