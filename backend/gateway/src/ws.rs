//! The WebSocket relay.
//!
//! `backend/api.py:1697` serves `/api/ws`, and it is not an optional surface: `console.js`
//! opens it and only falls back to polling if it cannot. `.claude/CLAUDE.md` records why that
//! matters — Apache was dropped for Caddy specifically because `mod_proxy_wstunnel` was never
//! enabled, so the rack's "pushed live over one socket" claim silently degraded to polling
//! while still being displayed. A gateway in front of `/api/*` that cannot carry the upgrade
//! rebuilds that bug exactly.
//!
//! **This cannot be done with `reqwest`.** The proxy in `proxy.rs` hands back a response body
//! stream; it never surfaces the upgraded socket underneath, so the handshake cannot be
//! completed through it. Worse, it fails *quietly*: `Connection` and `Upgrade` are hop-by-hop
//! headers (RFC 9110 §7.6.1) and are correctly stripped, so the request arrives at FastAPI as
//! an ordinary GET, misses the WebSocket route, and comes back **404** — which reads like a
//! missing route rather than a broken proxy. That was measured here before this file existed.
//!
//! So the relay is two independent WebSocket endpoints glued together: axum's server-side
//! upgrade facing the client, `tokio-tungstenite`'s client facing FastAPI, and a task pumping
//! frames each way until either side closes.

use axum::extract::ws::{Message as AxMsg, WebSocket, WebSocketUpgrade};
use axum::extract::{FromRequestParts, Request};
use axum::http::{header, HeaderMap, HeaderValue};
use axum::response::Response;
use futures_util::{SinkExt, StreamExt};
use tokio_tungstenite::tungstenite::protocol::CloseFrame as TgCloseFrame;
use tokio_tungstenite::tungstenite::Message as TgMsg;

use crate::error::AppError;
use crate::AppState;

/// Does this request want to become a WebSocket?
///
/// Both header checks are needed and both are case-insensitive by necessity: `Connection` is a
/// comma-separated list that legitimately reads `keep-alive, Upgrade`, so an equality test
/// against `"upgrade"` misses real browsers.
pub fn wants_upgrade(headers: &HeaderMap) -> bool {
    let has = |name: header::HeaderName, want: &str| {
        headers
            .get(name)
            .and_then(|v| v.to_str().ok())
            .is_some_and(|v| v.split(',').any(|p| p.trim().eq_ignore_ascii_case(want)))
    };
    has(header::CONNECTION, "upgrade") && has(header::UPGRADE, "websocket")
}

/// Accept the client upgrade, dial the upstream, and pump frames between them.
pub async fn relay(st: AppState, req: Request) -> Result<Response, AppError> {
    let (mut parts, _body) = req.into_parts();

    let path_and_query = parts
        .uri
        .path_and_query()
        .map(|p| p.as_str())
        .unwrap_or(parts.uri.path())
        .to_string();

    // http:// -> ws://, https:// -> wss://. The upstream config is written as an HTTP origin
    // because every other route uses it that way; only the scheme differs here.
    let base = st.cfg.api_upstream.clone();
    let target = if let Some(rest) = base.strip_prefix("https://") {
        format!("wss://{rest}{path_and_query}")
    } else if let Some(rest) = base.strip_prefix("http://") {
        format!("ws://{rest}{path_and_query}")
    } else {
        format!("ws://{base}{path_and_query}")
    };

    // The client-facing half of the handshake. This consumes the upgrade headers, which is
    // why it happens before anything that could fail on the upstream side: if we dialled
    // first and the upstream were down, the client would be left holding a request that has
    // neither upgraded nor been answered.
    let upgrade = WebSocketUpgrade::from_request_parts(&mut parts, &())
        .await
        .map_err(|e| AppError::BadRequest(format!("not a valid websocket upgrade: {e}")))?;

    // The forwarded chain, computed exactly as it is for a plain request. Without it every
    // socket looks to `api.py:1771` like it came from 127.0.0.1 and all of them share one
    // rate-limit bucket.
    let forwarded = crate::proxy::forwarded_value(&st, &parts);

    // `Origin` and `Cookie` are carried because they are the only two things `api.py` could
    // use to tell one caller from another; everything else in the client's header set is
    // either hop-by-hop or regenerated by the handshake below.
    let mut carry: Vec<(header::HeaderName, HeaderValue)> = Vec::new();
    for name in [header::ORIGIN, header::COOKIE, header::USER_AGENT] {
        if let Some(v) = parts.headers.get(&name) {
            carry.push((name, v.clone()));
        }
    }

    Ok(upgrade.on_upgrade(move |client| async move {
        if let Err(e) = pump(client, &target, forwarded, carry).await {
            // A relay failure after the upgrade cannot become a status code — the client is
            // already in WebSocket framing — so it has to be legible in the log instead.
            tracing::warn!(component = "gateway", target = %target, error = %e, "websocket relay ended");
        }
    }))
}

async fn pump(
    client: WebSocket,
    target: &str,
    forwarded: Option<String>,
    carry: Vec<(header::HeaderName, HeaderValue)>,
) -> anyhow::Result<()> {
    use tokio_tungstenite::tungstenite::client::IntoClientRequest;

    let mut req = target.into_client_request()?;
    if let Some(v) = forwarded {
        if let Ok(hv) = HeaderValue::from_str(&v) {
            req.headers_mut().insert("x-forwarded-for", hv);
        }
    }
    for (name, value) in carry {
        req.headers_mut().insert(name, value);
    }

    let (upstream, _resp) = tokio_tungstenite::connect_async(req).await?;

    let (mut up_tx, mut up_rx) = upstream.split();
    let (mut cl_tx, mut cl_rx) = client.split();

    // Both directions run concurrently and either one ending ends the pair. `/api/ws` is not
    // request/response: `api.py` pushes `rack` frames unprompted while the client sends
    // `chat` frames, so a half-duplex relay would stall the rack the moment a chat started.
    let to_upstream = async {
        while let Some(Ok(msg)) = cl_rx.next().await {
            let out = match msg {
                AxMsg::Text(t) => TgMsg::Text(t.as_str().into()),
                AxMsg::Binary(b) => TgMsg::Binary(b),
                AxMsg::Ping(b) => TgMsg::Ping(b),
                AxMsg::Pong(b) => TgMsg::Pong(b),
                AxMsg::Close(c) => {
                    let _ = up_tx
                        .send(TgMsg::Close(c.map(|f| TgCloseFrame {
                            code: f.code.into(),
                            reason: f.reason.as_str().into(),
                        })))
                        .await;
                    break;
                }
            };
            if up_tx.send(out).await.is_err() {
                break;
            }
        }
        let _ = up_tx.close().await;
    };

    let to_client = async {
        while let Some(Ok(msg)) = up_rx.next().await {
            let out = match msg {
                TgMsg::Text(t) => AxMsg::Text(t.as_str().into()),
                TgMsg::Binary(b) => AxMsg::Binary(b),
                TgMsg::Ping(b) => AxMsg::Ping(b),
                TgMsg::Pong(b) => AxMsg::Pong(b),
                TgMsg::Close(c) => {
                    let _ = cl_tx
                        .send(AxMsg::Close(c.map(|f| axum::extract::ws::CloseFrame {
                            code: f.code.into(),
                            reason: f.reason.as_str().into(),
                        })))
                        .await;
                    break;
                }
                // Raw frames are an internal tungstenite representation that never appears on
                // a read; there is nothing to translate and dropping one is not data loss.
                TgMsg::Frame(_) => continue,
            };
            if cl_tx.send(out).await.is_err() {
                break;
            }
        }
        let _ = cl_tx.close().await;
    };

    tokio::join!(to_upstream, to_client);
    Ok(())
}
