"""Why the derivative is what it is -- the rules, in the order they fire.

RavenCalc returns an answer. A student who typed `x**3*sin(x)` and got back
`x**2*(x*cos(x) + 3*sin(x))` has been told nothing about how to do the next one, and
"shows its work" is the whole difference between an instrument and an oracle.

The shape came from `incoming/RavenCalcServer_Christmas_20251224-1007`, which is prior
first-party work on this same problem and already emits rule names. This is written
against that shape rather than lifted from it, and it answers a strictly harder question:
that engine reports **which rules appeared somewhere** in the expression, unordered and
with nothing to tie a rule to the place it applied. This reports **which rule fired on
which subexpression, and what that subexpression differentiates to** -- so the output can
be read top to bottom as a derivation and every line can be checked on its own.

Nothing here calls the engine's own `diff` to decide what rule to name. The rule is read
off the node type, and the derivative of the part is computed for display only. That
matters: a step list generated by asking `diff` and narrating the answer would agree with
itself no matter how wrong the narration was.

**Structure only.** `steps_for_derivative` never simplifies, because simplification is
what destroys the correspondence between a step and the expression it is about --
`x*cos(x) + 3*x**2*sin(x)` factored to `x**2*(x*cos(x) + 3*sin(x))` no longer has a
product-rule shape anywhere in it.
"""
from __future__ import annotations

from typing import Any

from ..lib import symbolic

#: The derivative of each named function of one argument, written as a template rather
#: than computed, because the point of a step is to state the rule a reader can reuse.
#: Anything not named here still gets a step -- it falls to the generic branch, which
#: says which function it is and defers to the engine for the body. A missing entry is
#: therefore a less useful step, never a wrong one.
_KNOWN = {
    "sin": "d/dx sin(u) = cos(u) · u'",
    "cos": "d/dx cos(u) = -sin(u) · u'",
    "tan": "d/dx tan(u) = sec(u)^2 · u'",
    "exp": "d/dx e^u = e^u · u'",
    "log": "d/dx ln(u) = u' / u",
    "sinh": "d/dx sinh(u) = cosh(u) · u'",
    "cosh": "d/dx cosh(u) = sinh(u) · u'",
    "asin": "d/dx asin(u) = u' / sqrt(1 - u^2)",
    "acos": "d/dx acos(u) = -u' / sqrt(1 - u^2)",
    "atan": "d/dx atan(u) = u' / (1 + u^2)",
    "sqrt": "d/dx sqrt(u) = u' / (2·sqrt(u))",
}

#: A derivation of a thousand lines is not a derivation anybody reads, and a pathological
#: expression can nest arbitrarily deep. Truncation is reported in the record rather than
#: applied silently -- a step list that quietly stops is indistinguishable from one that
#: finished, which is the failure this repo keeps finding in its own test counts.
MAX_STEPS = 60


def _render(expression: Any) -> str:
    return symbolic.sstr(expression)


class _Walk:
    def __init__(self, variable) -> None:
        self.variable = variable
        self.steps: list[dict[str, str]] = []
        self.truncated = False

    def add(self, rule: str, node) -> None:
        if len(self.steps) >= MAX_STEPS:
            self.truncated = True
            return
        self.steps.append({
            "rule": rule,
            "at": _render(node),
            "gives": _render(symbolic.diff(node, self.variable, 1)),
        })

    def walk(self, node) -> None:
        x = self.variable

        # A subexpression the variable does not occur in has derivative zero, and every
        # rule below would still "apply" to it vacuously. Answering here keeps the
        # constant factor of `3*sin(x)` from generating a product-rule step nobody needs.
        if symbolic.is_constant(node, x):
            self.add("A part with no " + str(x) + " in it is constant: its derivative is 0", node)
            return

        if node == x:
            self.add(f"d/d{x} {x} = 1", node)
            return

        if isinstance(node, symbolic.Add):
            self.add("Sum rule: differentiate each term and add the results", node)
            for term in node.args:
                self.walk(term)
            return

        if isinstance(node, symbolic.Mul):
            # A constant multiple is a product in the engine's tree and is not a product
            # rule to a reader. Splitting them apart is the difference between a step
            # list that teaches and one that is technically correct.
            varying = [f for f in node.args if not symbolic.is_constant(f, x)]
            constant = [f for f in node.args if symbolic.is_constant(f, x)]
            if constant and len(varying) == 1:
                self.add("Constant multiple: the factor comes out front", node)
                self.walk(varying[0])
                return
            self.add("Product rule: d(u·v) = u'·v + u·v', taken across the factors", node)
            for factor in varying:
                self.walk(factor)
            return

        if isinstance(node, symbolic.Pow):
            base, exponent = node.args
            if symbolic.is_constant(exponent, x) and base == x:
                self.add("Power rule: d/dx x^n = n·x^(n-1)", node)
                return
            if symbolic.is_constant(exponent, x):
                self.add("Power rule with the chain rule: d(u^n) = n·u^(n-1)·u'", node)
                self.walk(base)
                return
            if symbolic.is_constant(base, x):
                self.add("Exponential: d/dx a^u = a^u · ln(a) · u'", node)
                self.walk(exponent)
                return
            self.add("Both base and exponent vary: rewrite as e^(v·ln u) first", node)
            self.walk(base)
            self.walk(exponent)
            return

        if isinstance(node, symbolic.Function) and len(node.args) == 1:
            name = type(node).__name__
            inner = node.args[0]
            template = _KNOWN.get(name)
            if template is None:
                self.add(f"Differentiate {name}, then multiply by the derivative of its "
                         f"argument (chain rule)", node)
            else:
                self.add(template, node)
            # A function of the variable itself has no inner derivative worth a line:
            # `sin(x)` would otherwise always be followed by "d/dx x = 1".
            if inner != x:
                self.walk(inner)
            return

        self.add("Differentiate this part directly", node)


def steps_for_derivative(expression, variable, order: int = 1) -> dict[str, Any]:
    """The derivation, as an ordered record.

    `order` above 1 restates the walk once per differentiation, against the expression as
    it stands at that point -- which is what a second derivative actually is, and why the
    rules named in round two are usually different from round one.
    """
    rounds: list[dict[str, Any]] = []
    current = expression
    truncated = False
    for n in range(1, order + 1):
        walk = _Walk(variable)
        walk.walk(current)
        truncated = truncated or walk.truncated
        current = symbolic.diff(current, variable, 1)
        rounds.append({
            "order": n,
            "of": _render(rounds[-1]["result"]) if rounds else _render(expression),
            "result": current,
            "steps": walk.steps,
        })
    return {
        "variable": str(variable),
        "rounds": [{"order": r["order"], "of": r["of"],
                    "result": _render(r["result"]), "steps": r["steps"]}
                   for r in rounds],
        "truncated": truncated,
        "note": ("the derivation stopped at "
                 f"{MAX_STEPS} steps -- the expression nests deeper than a readable "
                 "derivation") if truncated else "",
    }
