#!/usr/bin/env python3
"""Inject the live rack into the home page.

The rack is the launcher and the queue display at once. Its job is to answer, in one
glance, "can I use this right now?" -- and when the answer is no for one unit, to make
obvious that it is yes for three others. That is why it is a rack of separate units rather
than a single status line: 'chat is busy' and 'there is nothing to do here' should not look
the same.

Every light is driven by the live socket. Nothing animates on a timer for effect. On a site
whose entire argument is that it publishes measured numbers, a decorative activity LED
would be the one dishonest pixel on the page.

The rack names SyMoNeuRaL surfaces only. It used to carry `built on Qwen2.5-7B-Instruct`
per unit, which LICENSES.md called out as an Apache-2.0 condition rather than decoration;
that attribution now lives, in full and for every component, on /credits.html, and the
closing note links to it. Consolidating is fine -- §4 requires the notice to be present in
what we distribute, not repeated on every surface -- but it only works while the link is
there, so do not drop it. Note that the per-unit detail lines come from `/api/status`, not
from this file.

**The `<noscript>` fallback is generated from `backend/ROSTER.md`, not typed here.** It
used to carry exactly one row, `chat`, with a hardcoded `data-state="ready"` -- a claim about
this machine made by a file that has taken no reading, which is the decorative-indicator rule
above broken in the one place nobody looks. It now lists every row in the roster and asserts
nothing: no `data-state`, no state word, no per-unit spec. Those are readings, they come from
`/api/status`, and a fallback that runs because the socket is unavailable is precisely the
case where it does not have them. Identity is what it can honestly carry: what the unit is,
which bus it is on, how much rack it takes, and where to click.

Idempotent: the block lives between HTML markers and is replaced wholesale on each run.
"""
from __future__ import annotations

import pathlib
import re

# The generators live in tools/, so the repo root is one level up. This exact
# calculation has been wrong twice in this repo's history -- once when demo/ was
# flattened and once here -- and it fails *silently*, because the wrong parent is
# usually a directory that exists. Assert rather than trust it.
ROOT = pathlib.Path(__file__).resolve().parent.parent
assert (ROOT / "backend" / "server.py").is_file(), f"repo root not found at {ROOT}"
SITE = ROOT / "site"
INDEX = SITE / "index.html"

import sys as _sys
_sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import _art  # noqa: E402

# One reader for the roster, shared with `backend/test_roster.py`. Safe to import from a
# generator because there is no `backend/__init__.py` -- `apps` is a namespace package,
# so this pulls in a parser and nothing else. Importing `api.py` here would build every rate
# limiter, resolve the GPU governor and mount `site/`.
_sys.path.insert(0, str(ROOT / "backend"))
from registry.lib import roster  # noqa: E402

# The two renders that flank the rack. They are here rather than in a row of their own for
# the same reason the masthead's two are: the rack is 1120px wide inside a 1900px viewport
# and the gutters either side were empty at every width above 1280px, while a four-across
# row of the same images cost a full screen of scrolling between the pitch and the machine.
# These two are the hardware questions, next to the hardware they are about.
GUT_L = _art.gutter("cost", "A single graphics card resting on a workbench",
                    "Do you actually need<br>a data centre?", -1.5)
GUT_R = _art.gutter("build", "An engineer's desk with an open server chassis and a multimeter",
                    "Does it actually know how<br>your business works?", 1.5)

BEGIN = "<!-- ===== RACK:BEGIN (generated by build_rack.py) ===== -->"
END = "<!-- ===== RACK:END ===== -->"

POWER_GLYPH = ('<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.4" '
               'stroke-linecap="round"><path d="M12 3v9"/>'
               '<path d="M6.6 6.6a8 8 0 1 0 10.8 0"/></svg>')

# `slot` and `bus` are identity: how much rack the unit occupies and which bus it sits on.
# Neither is a reading, which is why they can be carried in a file. Bus is upper-cased for
# the plate, and RavenCalc's `cpu` matters -- it is the row that is green while the GPU is
# locked, so a fallback that dropped the bus would lose the one useful thing it can say.
FALLBACK = "".join(
    f'''          <a class="unit" href="{r["href"]}">
            <span class="leds"><i class="led"></i></span>
            <span class="pwr">{POWER_GLYPH}</span>
            <span class="uname"><b>{r["label"]}</b></span>
            <span class="ubus">{r["bus"].upper()}</span>
            <span class="ustate"><span class="txt">&mdash;</span><span class="slot">{r["slot"]}</span></span>
          </a>
'''
    for r in roster.rows()
)

RACK = f"""{BEGIN}
<section id="rack">
  <div class="wrap">
    <p class="shead"><img src="/terminal-64.png" alt="" width="22" height="22">Live Stack</p>
    <h2>The rack, as it is right now</h2>
    <p class="sub">
      Every surface on one workstation, pushed live over one socket. If a unit says busy,
      someone is genuinely using it and you are looking at a real queue. Pick a green one.
      A unit reading offline is telling you the truth as well: nothing here is lit for effect.
    </p>

    <!-- The fold control for the one-screen layout. It is a real <button> with aria-pressed
         rather than a CSS-only checkbox trick, because the state has to be announced. It is
         only shown when the one-screen layout is on: on a scrolling page there is nothing to
         save and hiding the attribution would be pure loss. console.js owns the behaviour
         and remembers the choice. -->
    <p class="rk-tools">
      <button type="button" class="rk-fold" id="rk-fold" aria-pressed="false"
              aria-controls="units">Show what each unit is running</button>
    </p>

  </div>

  <div class="rackrow">
    {GUT_L}

    <div class="rack">
      <div class="rail"><i></i><i></i><i></i><i></i><i></i></div>
      <div class="rail r"><i></i><i></i><i></i><i></i><i></i></div>

      <div class="units" id="units">
        <!-- Units are rendered from /api/status. Below is the pre-JS fallback, generated
             from backend/ROSTER.md: every row, identity only. No unit carries a
             data-state or a state word here, because this markup has measured nothing --
             the em dash is the same "no reading yet" mark the gauges below use. An unlit
             .led is the honest LED for a row whose state is unknown. -->
        <noscript>
{FALLBACK}        </noscript>
      </div>

      <div class="chassis">
        <div class="gauge">
          <label>VRAM <b id="g-vram">&mdash;</b></label>
          <div class="meterbar" id="g-vrambar"><i style="width:0%"></i></div>
        </div>
        <div class="gauge">
          <label>Power <b id="g-pwr">&mdash;</b></label>
          <div class="meterbar" id="g-pwrbar"><i style="width:0%"></i></div>
        </div>
        <div class="gauge chassis-id">
          <label>Chassis</label>
          <p class="cspec">
            <b>RTX 5070 Ti</b> <s>&middot;</s> <b>sm_120</b> <s>&middot;</s> <b id="g-temp">&mdash;</b><br>
            <span>PCIe Gen&nbsp;3 &times;8 &mdash; host capped</span>
          </p>
        </div>
      </div>
    </div>

    {GUT_R}
  </div>

  <div class="wrap">
    <p class="tnote" id="rack-note">
      One card, and the chat and image weight sets do not both fit in 15.92&nbsp;GiB &mdash; so a
      lock hands the GPU to exactly one surface at a time. RavenCalc is the exception: it is
      symbolic algebra on the CPU, so it is always green.
      Every unit above is a SyMoNeuRaL surface built on permissively licensed components;
      <a href="/credits.html">the full attribution is on one page</a>.
    </p>
  </div>
</section>

<script src="/console.js" defer></script>
{END}"""


def main() -> int:
    html = INDEX.read_text()

    if BEGIN in html and END in html:
        html = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), RACK, html, flags=re.S)
        where = "replaced"
    else:
        # Straight after the hero: the rack is the first thing worth touching, and it also
        # answers "is this thing real?" before any of the prose has to.
        anchor = '<!-- ===================== HARDWARE ===================== -->'
        if anchor not in html:
            print("could not find the hardware section anchor", flush=True)
            return 1
        html = html.replace(anchor, RACK + "\n\n" + anchor, 1)
        where = "inserted"

    INDEX.write_text(html)
    print(f"rack {where} in {INDEX.name} ({len(RACK):,} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
