#!/usr/bin/env python3
"""Render `ops/PORTS.tsv` into `docs/ops/PORTS.md`. The TSV is the record; this is the view.

    python3 tools/build_ports.py            # writes the doc
    python3 tools/build_ports.py --check    # exit 1 if the doc is stale

Generated rather than hand-written for the reason the rest of this repository generates its
manifests: a port that lives in prose is a port that goes stale, and this one has four
consumers. Run it twice and diff -- the generator must not accumulate its own output.
"""
from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
from registry import ports  # noqa: E402

OUT = ROOT / "docs" / "ops" / "PORTS.md"


def render() -> str:
    rows = ports.rows()
    delegated = ports.delegated_surfaces()
    lines = [
        "# Ports on this box",
        "",
        "**Generated by `tools/build_ports.py` from `ops/PORTS.tsv`. Do not hand-edit.**",
        "",
        "`ops/PORTS.tsv` is the single source of truth, and it has four readers: this document,",
        "`backend/ports.py` (the API and every surface process), the per-instance env file",
        "`ops/symoneural-surface@.service` uses, and `tools/smoke.py`. Adding a surface edits one",
        "file.",
        "",
        "| service | port | bind | surface | delegated | state |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| `{r['SERVICE']}` | {r['PORT']} | `{r['BIND']}` | "
                     f"{r['SURFACE'] if r['SURFACE'] != '-' else '—'} | "
                     f"{r['DELEGATED'] if r['DELEGATED'] != '-' else '—'} | {r['STATE']} |")
    lines += [
        "",
        "## Delegated surfaces",
        "",
        (f"**{', '.join(delegated)}** — a separate process owns these, and `backend/server.py` does "
         "not register their inline routes." if delegated else
         "**None.** The monolith answers every surface; `backend/server.py` registers every inline "
         "route. A surface becomes delegated by setting `DELEGATED yes` in the TSV *and* having a "
         "port — `apps/ports.py` refuses the combination without a port, because dropping the "
         "inline route while nothing else answered would 404 the surface as if it were a routing "
         "bug."),
        "",
        "## Notes, per row",
        "",
    ]
    for r in rows:
        if r["NOTE"] and r["NOTE"] != "-":
            lines.append(f"- **`{r['SERVICE']}`:{r['PORT']}** — {r['NOTE']}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.is_file() else ""
        if current == text:
            print(f"{OUT.relative_to(ROOT)} is current")
            return 0
        print(f"{OUT.relative_to(ROOT)} is STALE -- run tools/build_ports.py", file=sys.stderr)
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(ports.rows())} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
