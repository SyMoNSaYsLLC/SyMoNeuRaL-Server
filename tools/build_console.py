#!/usr/bin/env python3
"""Turn the home page into a control board.

The complaint was fair: the page was a document you scrolled through, and the numbers that
matter were spread across seven full-height sections. This collapses the whole thing into
one screen of instrument modules with the detail folded underneath.

Two rules govern the rewrite.

**Nothing is deleted.** Every table, figure and note survives -- the long sections become
`<details>` panels rather than being trimmed. The zero-data-loss rule applies to a layout
change exactly as it applied to the rebrand, and "we cut it because the page was long" is
how a spec sheet quietly becomes a brochure.

**Every module declares its provenance.** live = a sensor read just now; measured = a
benchmark we ran on this machine; projected = arithmetic from a measured or vendor figure.
That badge is the claim being made, and on a site whose whole argument is "we publish what
we measured" it belongs next to the number rather than in a footnote nobody reaches.

Idempotent: the console lives between markers and is replaced wholesale.
"""
from __future__ import annotations

import pathlib
import re

# The generators live in tools/, so the repo root is one level up. This exact
# calculation has been wrong twice in this repo's history -- once when demo/ was
# flattened and once here -- and it fails *silently*, because the wrong parent is
# usually a directory that exists. Assert rather than trust it.
ROOT = pathlib.Path(__file__).resolve().parent.parent
assert (ROOT / "backend" / "api.py").is_file(), f"repo root not found at {ROOT}"
SITE = ROOT / "site"
INDEX = SITE / "index.html"

BEGIN = "<!-- ===== CONSOLE:BEGIN (generated by build_console.py) ===== -->"
END = "<!-- ===== CONSOLE:END ===== -->"

# id -> (summary label, one-line spec shown beside it)
FOLDS = {
    "hardware":     ("Hardware specifications", "RTX 5070 Ti · full device table"),
    "interconnect": ("Host ↔ device transfer", "PCIe Gen 3 ×8 · the binding constraint"),
    "kernels":      ("Kernel characterisation", "measured throughput by operator"),
    "inference":    ("Inference architecture", "quantized model fit · decode projections"),
    "architecture": ("Service surfaces & residency", "tier residency · swap cost"),
    "environment":  ("Environment & build", "toolchain · hygiene parameters"),
}

ICONS = {
    "hardware": "/mark-32.png", "interconnect": "/sync-64.png", "kernels": "/calc-64.png",
    "inference": "/reinforce-64.png", "architecture": "/studio-64.png",
    "environment": "/terminal-64.png",
}


def module(src: str, tag: str, value: str, unit: str, sub: str,
           mid: str = "", meter: str = "", small: bool = False, plain: str = "") -> str:
    """One instrument module.

    `plain` says in ordinary English what the number means; `sub` keeps the engineering
    detail underneath it. Both are shown. The front page now argues to business owners
    rather than to CUDA programmers, and "atomics avoided 89.5x" tells that reader
    nothing -- but deleting the technical line to make room would be exactly the kind of
    quiet trimming this file was written to prevent.
    """
    idattr = f' id="{mid}"' if mid else ""
    unit_html = f"<u>{unit}</u>" if unit else ""
    meter_html = (f'<div class="meter" id="{meter}"><i style="width:0%"></i></div>'
                  if meter else "")
    cls = "val sm" if small else "val"
    plain_html = f'<div class="plain">{plain}</div>' if plain else ""
    return (f'<div class="mod" data-src="{src}">'
            f'<div class="tag"><s></s>{tag}</div>'
            f'<div class="{cls}"{idattr}>{value}{unit_html}</div>'
            f'{plain_html}'
            f'<div class="sub">{sub}</div>{meter_html}</div>')


