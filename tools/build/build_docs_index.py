#!/usr/bin/env python3
"""Generate the platform documentation index into `frontend/site/pages/documentation.html`.

    python3 tools/build/build_docs_index.py

## Why this exists, and why it is a generator rather than static markup

Handshake 6.1 added a hand-written index of the twenty-two scoped application documentation
pages to `frontend/site/pages/documentation.html`, guarded by two-way drift tests. That was the right call at
the time -- nothing generated that file as a whole, and an index that fetched `/api` at page
load would be blank whenever the API was down, which is the one thing a documentation index
must never be.

The reason it can now be generated is that the ownership registry it would have to duplicate
already exists and is safe to read at build time:

    backend/appdocs.py   imports only `dataclasses` and `html`
                              pulls in no fastapi, starlette, torch, uvicorn or api module
                              starts nothing, reads no file, opens no socket
                              22 applications, 8 runtimes, pure data
                              identical sha256 across separate processes

So this generator IMPORTS the one canonical registry and emits static markup. There is no
second registry, no build-time dependency on a running service, and the page still works with
the API down -- the three conditions that made generation the better option than the static
index it replaces.

**It does not import `api.py`.** Reading `appdocs` costs a namespace-package import of
`apps.appdocs` and nothing else; importing the serving module would build every rate limiter,
resolve the GPU governor and mount `site/`. `apps/roster.py` documents the same distinction
and for the same reason.

## What it will not do

It emits the INDEX only. It does not touch `/docs`, the scoped pages, the DispatchOS
customer-scoped page, or any other part of `documentation.html` outside its markers. Route
ownership, runtime parents and application children all come from the registry; this file
decides presentation and nothing else.

Idempotent: the block lives between HTML markers and is replaced wholesale on each run.
"""
from __future__ import annotations

import html as _html
import pathlib
import re
import sys

# The generators live in tools/, so the repo root is one level up. This exact calculation has
# been wrong twice in this repo's history and it fails SILENTLY, because the wrong parent is
# usually a directory that exists. Assert rather than trust it.
ROOT = next(_p for _p in pathlib.Path(__file__).resolve().parents if (_p / "backend" / "server.py").is_file())
assert (ROOT / "backend" / "server.py").is_file(), f"repo root not found at {ROOT}"
SITE = ROOT / "frontend" / "site"
PAGE = SITE / "pages" / "documentation.html"

# `backend/` on the path, not `backend/`: the registry is `apps.appdocs`, and importing it
# as a package member is what keeps `apps` a namespace package with no import side effects.
sys.path.insert(0, str(ROOT / "backend"))
from registry.lib import appdocs  # noqa: E402

BEGIN = "<!-- ===== DOCSINDEX:BEGIN (generated by build_docs_index.py) ===== -->"
END = "<!-- ===== DOCSINDEX:END ===== -->"


def e(s: str) -> str:
    return _html.escape(str(s), quote=True)


def _runtime_blocks() -> str:
    """One card per runtime, applications inside it, children nested under their parent.

    Ordered by `appdocs.RUNTIMES`, which is the controlling architecture's own order, so the
    page does not impose an ordering of its own. A runtime with no applications is skipped
    rather than rendered empty -- an empty card is a claim that something is missing.
    """
    by_runtime: dict[str, list] = {}
    for app in appdocs.APPLICATIONS:
        by_runtime.setdefault(app.runtime, []).append(app)

    out: list[str] = []
    for runtime in appdocs.RUNTIMES:
        here = by_runtime.get(runtime, [])
        if not here:
            continue
        parents = [a for a in here if a.parent is None]
        children: dict[str, list] = {}
        for a in here:
            if a.parent:
                children.setdefault(a.parent, []).append(a)

        rows: list[str] = []
        for app in parents:
            kids = children.get(app.id, [])
            kid_html = "".join(
                f'<a class="dx-kid" href="/docs/{e(k.id)}">{e(k.label)}</a>' for k in kids)
            rows.append(
                f'<a class="dx-app" href="/docs/{e(app.id)}">{e(app.label)}</a>'
                + (f'<span class="dx-kids">{kid_html}</span>' if kid_html else ""))

        # A child whose parent runs on a DIFFERENT runtime still needs a home on this card, or
        # it would be silently absent from the index while having a perfectly good page.
        for parent_id, kids in children.items():
            if any(a.id == parent_id for a in parents):
                continue
            for k in kids:
                rows.append(f'<a class="dx-app" href="/docs/{e(k.id)}">{e(k.label)}</a>')

        out.append(
            f'      <div class="dx-rt"><h3>{e(runtime)}</h3>'
            f'<p>{e(appdocs.RUNTIMES[runtime])}</p>\n        '
            + "\n        ".join(rows) + "\n      </div>")
    return "\n\n".join(out)


def block() -> str:
    n = len(appdocs.APPLICATIONS)
    return f"""{BEGIN}
<div class="wrap">
  <section class="dx" aria-labelledby="dx-h">
    <p class="eyebrow">Platform documentation</p>
    <h2 id="dx-h">Every application, and what runs it</h2>
    <p class="sub">
      This page is the <b>engineering manual</b> &mdash; the measurements behind the numbers,
      in the tabs below. The {n} links here are the <b>API documentation</b>: one scoped page
      per application, each carrying only that application&rsquo;s own routes, its runtime
      owner, its authentication boundary and its operational limits.
      <a href="/docs">/docs</a> is the platform-wide reference across all of them. Indented
      entries are child surfaces of the application above them &mdash; not runtimes of their
      own.
    </p>
    <div class="dx-grid">

{_runtime_blocks()}

    </div>
  </section>
</div>
{END}"""


def main() -> int:
    html = PAGE.read_text(encoding="utf-8")
    new = block()

    if BEGIN in html and END in html:
        html = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _m: new,
                      html, flags=re.S)
    else:
        # First run: the 6.1 hand-written block is replaced in place, so the page keeps its
        # structure and nothing is appended at the bottom. Matched on its own opening comment
        # and its closing `</div>` -- narrow on purpose, and it FAILS rather than guessing.
        old = re.search(
            r"<!-- ===== PLATFORM DOCS INDEX .*?<section class=\"dx\".*?</section>\s*</div>",
            html, flags=re.S)
        if not old:
            print("  documentation.html has neither the markers nor the 6.1 hand-written "
                  "block; refusing to guess where the index goes")
            return 1
        html = html[:old.start()] + new + html[old.end():]

    PAGE.write_text(html, encoding="utf-8")
    ids = [a.id for a in appdocs.APPLICATIONS]
    print(f"  docs index: {len(ids)} applications, "
          f"{len({a.runtime for a in appdocs.APPLICATIONS})} runtimes -> {PAGE.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
