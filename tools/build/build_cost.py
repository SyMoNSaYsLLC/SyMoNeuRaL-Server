#!/usr/bin/env python3
"""Inject the side-by-side cost comparison: this card against rented 48 GB class.

The point of this section is a single honest comparison, and it has to carry both halves or
it is an advertisement. The card wins on cost by a wide margin and loses on capacity by a
wide margin, and a reader deciding what to buy needs both numbers on the same screen.

Every cloud rate here comes from a real listing, is labelled as an observed rate rather than
a quote, and is dated -- these move monthly and a stale number presented as current is the
same failure as an unmeasured benchmark presented as measured.

Idempotent: lives between markers, replaced wholesale.
"""
from __future__ import annotations

import pathlib
import re

# The generators live in tools/, so the repo root is one level up. This exact
# calculation has been wrong twice in this repo's history -- once when demo/ was
# flattened and once here -- and it fails *silently*, because the wrong parent is
# usually a directory that exists. Assert rather than trust it.
ROOT = next(_p for _p in pathlib.Path(__file__).resolve().parents if (_p / "backend" / "server.py").is_file())
assert (ROOT / "backend" / "server.py").is_file(), f"repo root not found at {ROOT}"
SITE = ROOT / "frontend" / "site"
INDEX = SITE / "documentation.html"

BEGIN = "<!-- ===== COST:BEGIN (generated by build_cost.py) ===== -->"
END = "<!-- ===== COST:END ===== -->"

CARD_COST = 1000
POWER_W = 300
KWH = 0.15
RUN_HR = POWER_W / 1000 * KWH          # $0.045/hr at full tilt

HOURS = 8760                           # a year, running continuously

# The utilisation assumption is a NAMED CONSTANT and is printed in the caption, deliberately.
# backend/studio/docs/symon-ml-review.md §5 is the reason: a pitch arrived claiming an 8-GPU node
# generates "~$5,800/month", and the arithmetic only closed at 59.9% occupancy -- an
# assumption the document never stated. That is the number a sceptical reader attacks first,
# and "we assumed 60%" is a far stronger answer given up front than extracted under
# questioning. The table below prints BOTH 100% and this figure, so nothing is unstated.
UTIL = 0.60


def power_yr(watts: float) -> float:
    """Card TDP only, at the same $0.15/kWh used for this machine. No cooling overhead."""
    return watts / 1000 * HOURS * KWH


# (label, variant, memory, bandwidth, watts, buy_lo, buy_hi, rate, rate_lo, rate_hi, providers, mark)
#
# NOTHING in this table is measured here. No H100 has ever been in this box. Specs are
# vendor, read off NVIDIA's own product pages on 2026-08-17; rates are observed market
# medians; every money column is projected arithmetic.
#
# Going first-party for the specs was not pedantry. An aggregator consulted the same day
# reported the H200 SXM at "~350 W" -- it is 700 W -- and the A100 80 GB at 1.555 TB/s,
# which is the 40 GB part's figure; the 80 GB is 2,039 GB/s. Either would have propagated
# silently into every derived number in the row.
#
# Every rate comes from ONE aggregator, getdeploying.com, read 2026-08-17, because the rows
# have to be comparable to each other. A first draft mixed sources and produced a table in
# which the A100 out-earned the H100 -- an artefact of the sources, not of the market.
FLEET = [
    ("L40S", "PCIe", "48 GB GDDR6", "864 GB/s", 350,
     7569, 10584, 1.54, 0.55, 3.00, 31, ""),
    ("A100", "SXM, 80 GB", "80 GB HBM2e", "2,039 GB/s", 400,
     7000, 15000, 1.76, 1.09, 4.03, 42, ""),
    ("H100", "SXM", "80 GB HBM3", "3.35 TB/s", 700,
     25000, 40000, 3.35, 2.19, 14.19, 53, ""),
    ("H200", "SXM", "141 GB HBM3e", "4.8 TB/s", 700,
     30000, 40000, 4.37, 3.00, 7.91, 37, ""),
    ("B200", "HGX / DGX", "180 GB HBM3e", "~8 TB/s", 1000,
     37500, 62500, 7.11, 3.75, 16.11, 28, "&Dagger;"),
]


def spec(text: str) -> str:
    """The second line in a card cell. Inline-styled on purpose -- CLAUDE.md records three
    separate bugs from generic class names colliding across components, and this needs
    exactly one new visual treatment, not a new global class."""
    return (f'<span style="display:block;margin-top:4px;color:var(--faint);'
            f'font-size:var(--t7);font-weight:400;line-height:1.5">{text}</span>')


# Six of the seven columns are `.num`, and `td.num` is `white-space:nowrap`. In an auto-layout
# table that means those six take their content width first and the ONLY column that can
# absorb the shortfall is this one -- which it did by wrapping "RTX 5070 Ti -- this machine"
# down five lines and the spec line down six, at 145px a row. Rendered and measured; it is not
# something the markup suggests. A floor on the first column fixes it without nowrap, which
# would have traded a squeezed column for a clipped one.
COL1 = "min-width:216px"


def fleet_rows() -> str:
    out = [
        '<tr style="background:rgba(46,224,138,.06)">'
        f'<td class="k" style="{COL1}"><b>RTX 5070 Ti</b>'
        + spec('this machine &middot; 15.92 GiB &middot; 752 GB/s measured &middot; 300 W') +
        '</td>'
        f'<td class="num"><b>${CARD_COST:,}</b></td>'
        '<td class="num">&mdash;</td>'
        '<td class="num">&mdash;</td>'
        '<td class="num">&mdash;</td>'
        f'<td class="num">${power_yr(POWER_W):,.0f}</td>'
        '<td class="num">not rentable&nbsp;&dagger;</td></tr>'
    ]
    for label, variant, mem, bw, watts, lo, hi, rate, r_lo, r_hi, n, mark in FLEET:
        gross_full = rate * HOURS
        gross_util = gross_full * UTIL
        net = gross_util - power_yr(watts)
        out.append(
            f'<tr><td class="k" style="{COL1}">{label} '
            f'<span style="color:var(--faint);font-weight:400">{variant}</span>'
            + spec(f'{mem} &middot; {bw} &middot; {watts} W') +
            f'</td>'
            f'<td class="num">${lo:,}&ndash;${hi:,}{mark}</td>'
            f'<td class="num">${rate:.2f}'
            + spec(f'${r_lo:.2f}&ndash;${r_hi:.2f}, {n} providers') +
            f'</td>'
            f'<td class="num"><em>${gross_full:,.0f}</em></td>'
            f'<td class="num"><em>${gross_util:,.0f}</em></td>'
            f'<td class="num">${power_yr(watts):,.0f}</td>'
            f'<td class="num">{lo / net:.1f}&ndash;{hi / net:.1f} yr</td></tr>')
    return "\n          ".join(out)

# (provider, vram, gpus, host, $/hr) -- observed listings, August 2026
