#!/usr/bin/env python3
"""Build the constellation on /build.html: nineteen renders wired to four questions.

This block began life on the front page and did not fit there. The gutters beside a
readable centre column are too narrow to hold a constellation, and below 1280px the
absolutely-positioned renders collapsed into a vertical stack down the left edge -- which
is exactly what a visitor saw. /build.html is a short page with real vertical space, and
the four objections here are precisely the ones someone who clicked "Have one built" is
carrying. So it moved rather than being deleted.

Two things are load-bearing:

**The lines are SVG, not CSS.** Each is drawn in a 0-100 viewBox with
`preserveAspectRatio="none"` so the constellation stretches with the block, plus
`vector-effect="non-scaling-stroke"` so the stroke stays hairline instead of smearing when
the box is wider than it is tall.

**Every image is a real render from this machine**, watermarked with its model, seed and
the seconds it took. `tools/build_gallery.py` makes them, and each one links to its full
768px file so the watermark can actually be read.

Its CSS namespace is `.sky`, not `.band`. The homepage band is a different object now and
this stylesheet has three separate incidents of a second definition silently eating a
first (`.bar`, `.live`, `.sub`). Nothing is shared but the word "art".

Idempotent: the block lives between markers and is replaced wholesale.
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import _art  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
assert (ROOT / "backend" / "api.py").is_file(), f"repo root not found at {ROOT}"
SITE = ROOT / "site"
PAGE = SITE / "build.html"

BEGIN = "<!-- ===== SKY:BEGIN (generated by tools/build_sky.py) ===== -->"
END = "<!-- ===== SKY:END ===== -->"

# Four clusters. Each is a question anchored at (x, y) in percent, with the renders that
# hang off it. Sizes vary deliberately: a uniform grid reads as a contact sheet, uneven
# sizes read as a constellation.
#   (slug, x%, y%, width px, rotation deg)
CLUSTERS = [
    {
        "q": "What if your data never<br>left the building?",
        "qx": 15.5, "qy": 33, "align": "left",
        "art": [
            ("owns", 6.0, 11.0, 59, -5),
            ("vault", 15.5, 15.0, 43, 4),
            ("chip", 22.5, 24.0, 41, -3),
            ("private", 3.5, 27.0, 50, 6),
            ("map", 11.0, 45.0, 46, -4),
            ("cable", 21.0, 48.0, 38, 5),
        ],
    },
    {
        "q": "Who owns your model when<br>the invoice stops?",
        "qx": 17.5, "qy": 71, "align": "left",
        "art": [
            ("yours", 5.0, 60.0, 55, 5),
            ("box", 13.5, 63.0, 39, -6),
            ("token", 24.0, 65.0, 38, 3),
            ("hands", 8.0, 83.0, 49, -4),
            ("clock", 19.5, 86.0, 41, 6),
        ],
    },
    {
        "q": "Do you actually need<br>a data centre?",
        "qx": 81, "qy": 30, "align": "right",
        "art": [
            ("cost", 72.0, 11.0, 56, 5),
            ("rack2", 84.5, 13.0, 42, -4),
            ("gpu", 92.5, 21.0, 46, 3),
            ("desk", 75.5, 25.0, 38, -6),
            ("meter", 88.0, 37.0, 50, 4),
        ],
    },
    {
        # The question here used to be "What would you ask an AI that nobody else can see?",
        # which Garrett read as meaningless and he was right: it asks the visitor to imagine
        # a secret rather than to notice a cost. The other three name a real objection --
        # where the data goes, who owns the model, what the hardware costs -- and this one
        # now names the fourth: whether the thing knows anything about your business.
        "q": "Does it actually know how<br>your business works?",
        "qx": 80, "qy": 73, "align": "right",
        "art": [
            ("fast", 73.0, 60.0, 52, -5),
            ("build", 85.5, 62.0, 41, 4),
            ("token2", 93.0, 70.0, 38, -3),
        ],
    },
]

ALT = {
    "owns": "A server rack glowing in a dark office", "cost": "A graphics card on a workbench",
    "private": "A locked door inside a server room", "fast": "Light trails down a data centre aisle",
    "yours": "A hand holding a labelled drive", "build": "An engineer's desk with an open chassis",
    "gpu": "A graphics card fan blade", "rack2": "Three stacked server units",
    "cable": "Coiled network cables", "chip": "A silicon die under magnification",
    "desk": "A laptop beside a small server tower", "meter": "An analogue power meter",
    "vault": "A heavy safe door ajar", "map": "A network graph of glowing nodes",
    "box": "A shipping box under one light", "token": "Streams of glowing particles",
    "hands": "A handshake in front of a server rack", "clock": "A clock in a dark server room",
}


def build() -> str:
    arts, lines, qs = [], [], []
    for i, c in enumerate(CLUSTERS):
        qs.append(
            f'  <p class="q q{i}" style="left:{c["qx"]}%;top:{c["qy"]}%;text-align:{c["align"]}">'
            f'{c["q"]}</p>'
        )
        for slug, x, y, w, rot in c["art"]:
            src = slug if (SITE / f"art-{slug}.png").is_file() else slug.rstrip("2")
            meta = SITE / f"art-{src}.json"
            prompt = seed = secs = ""
            if meta.is_file():
                d = json.loads(meta.read_text())
                prompt, seed, secs = d.get("prompt", ""), d.get("seed", ""), d.get("seconds", "")
            esc = prompt.replace('"', "&quot;")
            # The model and step count used to be typed in here rather than read from the
            # sidecar, so this caption could disagree with the watermark on the image it
            # captions. Both now come from _art.provenance().
            cap = (f'<figcaption><q>{prompt}</q>'
                   f'<span>{_art.provenance(src)}</span></figcaption>') if prompt else ""
            iw, ih = _art.dims(src)
            arts.append(
                f'    <a class="art" href="/art-{src}.png" '
                f'style="left:{x}%;top:{y}%;width:{w}px;transform:rotate({rot}deg);'
                f'--unrot:{-rot}deg" '
                f'title="{esc}" data-prompt="{esc}" data-seed="{seed}" data-secs="{secs}" '
                f'aria-label="Open the full render: {esc}">'
                f'<img src="/art-{src}.png" alt="{ALT.get(slug, "Rendered by SyMoNeuRaL Image")}, '
                f'rendered by SyMoNeuRaL Image" loading="lazy" width="{iw}" height="{ih}">'
                f'{cap}</a>'
            )
            # from the question anchor to the centre of the render
            lines.append(f'    <line x1="{c["qx"]}" y1="{c["qy"]}" x2="{x}" y2="{y}" />')

    return f"""{BEGIN}
<div class="sky">
  <svg class="sky-lines" viewBox="0 0 100 100" preserveAspectRatio="none" aria-hidden="true">
{chr(10).join(lines)}
  </svg>

  <div class="sky-art">
{chr(10).join(arts)}
  </div>

{chr(10).join(qs)}

  <div class="sky-mid">
    <h2>Four questions we get<br>on every single call.</h2>
    <p class="sky-lede">
      None of them are about model architecture. They are about where the data sits, who
      owns the thing when you stop paying, what the hardware actually costs, and whether it
      knows the first thing about your business. <b>We answer all four in writing, with
      numbers, before you spend anything.</b>
    </p>
    <p class="sky-foot">
      Every picture here was drawn by <b>SyMoNeuRaL Image</b> on the card in our workshop
      &mdash; same four steps you get, seed stamped on each one. Nothing is stock.
      Click any of them to read it.
    </p>
  </div>
</div>
{END}"""


def main() -> int:
    html = PAGE.read_text()
    block = build()
    if BEGIN in html and END in html:
        html = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, html, flags=re.S)
        where = "replaced"
    else:
        anchor = "<!-- ===================== FOOTER ===================== -->"
        i = html.index(anchor)
        html = html[:i] + block + "\n\n" + html[i:]
        where = "inserted"
    PAGE.write_text(html)
    n = sum(len(c["art"]) for c in CLUSTERS)
    print(f"sky {where} in build.html: {n} renders, {len(CLUSTERS)} questions, {n} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
