BADGE = {
    "impl": ("running", "ok"),
    "measured": ("measured", "meas"),
    "na": ("not applicable", "na"),
    "absent": ("not implemented", "absent"),
}


def rows(items):
    out = []
    for name, status, note in items:
        label, cls = BADGE[status]
        out.append(
            f'<tr><td class="k">{name}</td>'
            f'<td class="num"><span class="badge {cls}">{label}</span></td>'
            f'<td>{note}</td></tr>')
    return "\n          ".join(out)


def layer_block(title, icon, blurb, comps):
    cells = "\n        ".join(
        f'<div class="scell" data-s="{s}"><b>{n}</b><span>{run}</span>'
        f'<small>{note}</small></div>'
        for n, run, s, note in comps)
    return f'''      <div class="layer">
        <div class="lhead"><img src="{icon}" alt="" width="20" height="20">
          <b>{title}</b><span>{blurb}</span></div>
        <div class="lgrid">
        {cells}
        </div>
      </div>'''


