"""The derivation says which rule fired where -- and stays honest when it cannot.

The assertion that matters most here is `TheStepsAreReadOffTheTreeTests`: a step list
generated by asking the engine for the answer and then narrating it would agree with
itself no matter how wrong the narration was, and every other test in this file would
still pass. So one test differentiates a product and demands the word *product*, and
another demands that a constant multiple is NOT called a product rule -- which is the
one place a lazily-written walk gets it wrong, because `3*sin(x)` is a `Mul` node.
"""
from __future__ import annotations

import pathlib
import sys
import unittest


from ravencalc.apps import ravencalc  # noqa: E402
from ravencalc.apps import steps  # noqa: E402
from ravencalc.lib import symbolic  # noqa: E402
from ravencalc.apps.ravencalc import parse, make_symbols  # noqa: E402


def variable_of(expression, name: str):
    """Pick the symbol out of the parsed expression rather than minting a fresh one.

    `make_symbols(None)` returns an empty dict on purpose -- the absence of an assumption
    is itself an assumption and belongs to the caller -- so the symbol the parser built is
    the only one that compares equal to what is in the tree. A `Symbol("x")` made here
    would carry different assumptions and silently match nothing.
    """
    for symbol in expression.free_symbols:
        if str(symbol) == name:
            return symbol
    raise AssertionError(f"{name} does not occur in {expression}")


def record(text: str, var: str = "x", order: int = 1):
    expression = parse(text, make_symbols(None))
    return steps.steps_for_derivative(expression, variable_of(expression, var), order)


def rules(text: str, var: str = "x", order: int = 1) -> list[str]:
    rec = record(text, var, order)
    return [s["rule"] for r in rec["rounds"] for s in r["steps"]]


class TheStepsAreReadOffTheTreeTests(unittest.TestCase):
    def test_a_product_names_the_product_rule(self):
        self.assertTrue(any("Product rule" in r for r in rules("x**3*sin(x)")))

    def test_a_constant_multiple_is_not_called_a_product(self):
        """`3*sin(x)` is a Mul node, so the naive walk calls it a product rule.

        It is not one to a reader, and naming it one is the step that teaches the wrong
        thing -- which is worse than no step at all.
        """
        got = rules("3*sin(x)")
        self.assertTrue(any("Constant multiple" in r for r in got), got)
        self.assertFalse(any("Product rule" in r for r in got), got)

    def test_a_sum_names_the_sum_rule_and_then_each_term(self):
        got = rules("x**2 + sin(x)")
        self.assertIn("Sum rule: differentiate each term and add the results", got[0])
        self.assertTrue(any("Power rule" in r for r in got))
        self.assertTrue(any("sin(u)" in r for r in got))

    def test_a_composite_names_the_chain_rule_and_walks_into_the_argument(self):
        rec = record("sin(x**2)")
        at = [s["at"] for r in rec["rounds"] for s in r["steps"]]
        self.assertIn("sin(x**2)", at)
        self.assertIn("x**2", at, "the walk never entered the argument")

    def test_a_bare_variable_inside_a_function_gets_no_pointless_step(self):
        """`sin(x)` must not be followed by "d/dx x = 1". True of the answer, useless."""
        at = [s["at"] for r in record("sin(x)")["rounds"] for s in r["steps"]]
        self.assertEqual(at, ["sin(x)"], at)


class EveryStepIsCheckableOnItsOwnTests(unittest.TestCase):
    def test_each_step_reports_the_derivative_of_the_part_it_names(self):
        """`gives` must be the derivative of `at`, not a slice of the final answer.

        Recomputed here from the rendered text, so a step whose `gives` was copied from
        the parent expression fails: the two are equal only when the step is honest.
        """
        rec = record("x**3*sin(x) + 5*x")
        for r in rec["rounds"]:
            for s in r["steps"]:
                part = parse(s["at"], make_symbols(None))
                expected = symbolic.diff(part, variable_of(part, "x"), 1) \
                    if part.free_symbols else symbolic.Integer(0)
                self.assertEqual(
                    symbolic.sstr(expected), s["gives"],
                    f"step {s['rule']!r} on {s['at']} claims {s['gives']}")


class ItRefusesToRunAwayTests(unittest.TestCase):
    def test_a_deeply_nested_expression_truncates_and_says_so(self):
        """A step list that quietly stops is indistinguishable from one that finished."""
        deep = " + ".join(f"x**{n}*sin(x)" for n in range(1, 40))
        rec = record(deep)
        total = sum(len(r["steps"]) for r in rec["rounds"])
        self.assertEqual(total, steps.MAX_STEPS)
        self.assertTrue(rec["truncated"])
        self.assertIn("stopped at", rec["note"])

    def test_an_ordinary_expression_is_not_marked_truncated(self):
        rec = record("x**3*sin(x)")
        self.assertFalse(rec["truncated"])
        self.assertEqual(rec["note"], "")


class HigherOrderRestartsTheWalkTests(unittest.TestCase):
    def test_a_second_derivative_walks_the_first_derivative(self):
        """Asserted on the STEPS, not only on the answer.

        This test was written asserting `of` and `result` alone, and
        `tools/audit/prove_ravencalc_steps.py` showed it surviving the exact defect it exists
        to catch: re-walking the ORIGINAL expression every round still produces the right
        `result`, because the result comes from the engine and not from the walk. The
        rules are the only place the difference shows. `x**3` walks to a bare power rule;
        its derivative `3*x**2` walks to a constant multiple AND a power rule, which the
        first round cannot produce.
        """
        rec = record("x**3", order=2)
        self.assertEqual([r["order"] for r in rec["rounds"]], [1, 2])
        self.assertEqual(rec["rounds"][1]["of"], "3*x**2")
        self.assertEqual(rec["rounds"][1]["result"], "6*x")

        first = [s["rule"] for s in rec["rounds"][0]["steps"]]
        second = [s["rule"] for s in rec["rounds"][1]["steps"]]
        self.assertTrue(any("Power rule" in r for r in first), first)
        self.assertFalse(any("Constant multiple" in r for r in first), first)
        self.assertTrue(any("Constant multiple" in r for r in second),
                        f"round 2 walked the original, not the first derivative: {second}")
        self.assertEqual([s["at"] for s in rec["rounds"][1]["steps"]][0], "3*x**2")


class TheRequestPathCarriesItTests(unittest.TestCase):
    """A derivation nobody can ask for is dead code, so the wire format is asserted too."""

    def ask(self, **fields):
        return ravencalc.run_request(
            {"operation": "differentiate", "expression": "x**3*sin(x)",
             "variable": "x", **fields})

    def test_steps_true_returns_a_derivation_beside_the_answer(self):
        doc = self.ask(steps=True)
        self.assertEqual(doc["result"]["text"], "x**3*cos(x) + 3*x**2*sin(x)")
        self.assertIn("derivation", doc)
        self.assertTrue(any("Product rule" in s["rule"]
                            for s in doc["derivation"]["rounds"][0]["steps"]))

    def test_the_default_result_document_is_unchanged(self):
        """Every existing caller parses this document. The new key must not appear unasked.

        symonsaymath reads these results, and a key that materialises on its own is a
        silent contract change -- the kind that is found in production rather than here.
        """
        self.assertNotIn("derivation", self.ask())

    def test_the_echoed_request_says_steps_were_asked_for(self):
        """`as_record` is what lets a caller show what was actually computed."""
        self.assertTrue(self.ask(steps=True)["request"]["steps"])
        self.assertNotIn("steps", self.ask()["request"])

    def test_asking_for_steps_on_an_operation_that_has_none_is_refused(self):
        """Refused, not ignored. A missing `derivation` key reads as "no interesting
        steps" rather than "this operation cannot produce them"."""
        with self.assertRaises(ravencalc.RavenCalcError) as caught:
            ravencalc.run_request({"operation": "simplify", "expression": "x + x",
                                   "steps": True})
        self.assertIn("available for differentiate", str(caught.exception))

    def test_a_non_boolean_steps_field_is_a_validation_problem(self):
        with self.assertRaises(ravencalc.RavenCalcError) as caught:
            self.ask(steps="yes")
        self.assertIn("steps must be true or false", str(caught.exception))

    def test_the_derivation_uses_the_symbol_the_answer_was_computed_with(self):
        """`Symbol('x', real=True)` and `Symbol('x')` are different symbols to the engine.

        A derivation that re-parsed the expression would build the second one and narrate
        a different question -- silently, and only for callers who sent assumptions.
        """
        doc = ravencalc.run_request({
            "operation": "differentiate", "expression": "x**3*sin(x)", "variable": "x",
            "assume": {"x": ["real"]}, "steps": True})
        # `assumed` reports the closure sympy derived, not the flag that was sent --
        # asking for `real` also yields complex, finite, hermitian and the rest.
        self.assertIn("real", doc["assumed"]["x"])
        steps_seen = doc["derivation"]["rounds"][0]["steps"]
        self.assertTrue(steps_seen, "the derivation was empty under an assumption")
        self.assertEqual(steps_seen[0]["gives"], doc["result"]["text"])


if __name__ == "__main__":
    unittest.main()
