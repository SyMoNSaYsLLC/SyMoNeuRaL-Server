# Build the first-party symoneural-web runtime, reproducibly, and generate its SBOM and
# third-party notices.
#
#   ops/build-symoneural-web.sh              build into web/symoneural-web/build/
#   ops/build-symoneural-web.sh --check      report the toolchain and stop
#
# ## -trimpath is mandatory here, and the reason is measured rather than assumed
#
# Two clean builds of this module in separate directories with separate build caches produced
# DIFFERENT digests without it and byte-IDENTICAL digests with it:
#
#     without -trimpath   693cec78f9f6602ee18b292ba8ca3cd74e86cbe206c984e7c3abed9ab4c78dd7
#     with    -trimpath   9e9887b49908ecf9c47d64e6d2176488ff81605d5fc7f91d9a83e16898de2834  (A)
#     with    -trimpath   9e9887b49908ecf9c47d64e6d2176488ff81605d5fc7f91d9a83e16898de2834  (B)
#
# The cause is Go embedding absolute source and module-cache paths in the binary. That is
# nondeterminism from the environment rather than from the source, so it is removed rather
# than explained away every time somebody re-runs the build.
#
# ## The binary is NOT committed
#
# `.gitignore` keeps build output out of the tree. What travels in Git is this script, the
# source, `go.mod`, `go.sum` and the generated manifests -- which together are enough to
# reproduce the artifact and to prove that a given file on disk came from them.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/web/symoneural-web"
OUT="$SRC/build"
GOBIN_DIR=/usr/lib/go-1.24/bin
export PATH="$GOBIN_DIR:$PATH"
export GOMODCACHE="${GOMODCACHE:-$HOME/go/pkg/mod}"
export GOFLAGS=-mod=readonly          # refuse to silently edit go.mod during a release build

say() { printf '  %s\n' "$*"; }

command -v go >/dev/null || { echo "go toolchain not found on PATH" >&2; exit 1; }
say "go            : $(go version)"
say "GOROOT        : $(go env GOROOT)"
say "GOMODCACHE    : $GOMODCACHE"
say "GOFLAGS       : $GOFLAGS"
[ "${1:-}" = "--check" ] && { say "check only."; exit 0; }

# ---------------------------------------------------------------- provenance inputs
cd "$ROOT"
GIT_COMMIT="$(git rev-parse HEAD 2>/dev/null || echo unknown)"
# Dirty state is reported, never hidden. A release built from a dirty tree is a real thing
# that happens; a release that CLAIMS to be clean when it was not is the problem.
if [ -z "$(git status --porcelain 2>/dev/null)" ]; then GIT_DIRTY=false; else GIT_DIRTY=true; fi
LICENSE_PATH="$ROOT/LICENSE"
LICENSE_SHA="$(sha256sum "$LICENSE_PATH" | cut -d' ' -f1)"
NOTICES_REL="THIRD_PARTY_NOTICES.md"
VERSION="$(cat "$SRC/VERSION" 2>/dev/null || echo 0.1.0)"

mkdir -p "$OUT"

# ---------------------------------------------------------------- SBOM + notices
# Generated from the REAL module graph, not from a hand-kept list: `go list -m all` is what
# the linker actually consumed, so the inventory cannot drift from the binary.
say "generating module inventory and third-party notices ..."
cd "$SRC"
go list -m -f '{{.Path}}	{{.Version}}' all 2>/dev/null | grep -v '^github.com/symonsays/symoneural-web' \
  | sort > "$OUT/go-modules.tsv"
MODCOUNT=$(wc -l < "$OUT/go-modules.tsv")

{
  echo "# THIRD_PARTY_NOTICES — symoneural-web"
  echo
  echo "Generated by \`ops/build-symoneural-web.sh\` from the real Go module graph"
  echo "(\`go list -m all\`) at build time. It is not a hand-kept list and cannot drift from"
  echo "the binary it ships beside."
  echo
  echo "**symoneural-web is SyMoNeuRaL-authored source that IMPORTS these modules.** The"
  echo "SyMoNeuRaL Proprietary Licence covers the SyMoNeuRaL-authored portion only and does"
  echo "not replace, override or restate any licence below. Every module here is the work of"
  echo "its own authors."
  echo
  echo "The principal embedded component is **Caddy** (\`github.com/caddyserver/caddy/v2\`),"
  echo "licensed **Apache-2.0**, authored by the Caddy authors and not by SyMoNeuRaL."
  echo
  echo "| # | module | version |"
  echo "|---|---|---|"
  n=0
  while IFS=$'\t' read -r p v; do
    n=$((n+1)); printf '| %d | `%s` | `%s` |\n' "$n" "$p" "$v"
  done < "$OUT/go-modules.tsv"
  echo
  echo "**Total third-party Go modules: $MODCOUNT.**"
  echo
  echo "Full licence text for each module is present in the Go module cache under"
  echo "\`\$GOMODCACHE/<module>@<version>/\` and is reproducible offline from \`go.sum\`."
} > "$OUT/$NOTICES_REL"
say "modules       : $MODCOUNT  -> $OUT/$NOTICES_REL"

# ---------------------------------------------------------------- build
BUILD_ID="$(printf '%s|%s|%s|%s' "$GIT_COMMIT" "$GIT_DIRTY" "$VERSION" "$(sha256sum go.sum | cut -d' ' -f1)" | sha256sum | cut -c1-16)"
LD="-X main.version=$VERSION -X main.gitCommit=$GIT_COMMIT -X main.gitDirty=$GIT_DIRTY"
LD="$LD -X main.buildID=$BUILD_ID -X main.licenseSHA=$LICENSE_SHA"
LD="$LD -X main.licensePath=$LICENSE_PATH -X main.noticesPath=$OUT/$NOTICES_REL"

say "building (-trimpath, stamped) ..."
go build -trimpath -ldflags "$LD" -o "$OUT/symoneural-web" .

# Cargo-style hardlink breaking is not needed for Go, but the independence check is:
[ -L "$OUT/symoneural-web" ] && { echo "refusing: output is a symlink" >&2; exit 1; }

SHA="$(sha256sum "$OUT/symoneural-web" | cut -d' ' -f1)"
{
  echo "{"
  echo "  \"component\": \"symoneural-web\","
  echo "  \"product\": \"SyMoNeuRaL\","
  echo "  \"version\": \"$VERSION\","
  echo "  \"git_commit\": \"$GIT_COMMIT\","
  echo "  \"git_dirty\": $GIT_DIRTY,"
  echo "  \"build_id\": \"$BUILD_ID\","
  echo "  \"sha256\": \"$SHA\","
  echo "  \"size_bytes\": $(stat -c %s "$OUT/symoneural-web"),"
  echo "  \"license_id\": \"LicenseRef-SyMoNeuRaL-Proprietary\","
  echo "  \"license_sha256\": \"$LICENSE_SHA\","
  echo "  \"third_party_modules\": $MODCOUNT,"
  echo "  \"go_version\": \"$(go version | awk '{print $3}')\","
  echo "  \"trimpath\": true,"
  echo "  \"upstream_engine\": \"github.com/caddyserver/caddy/v2 (Apache-2.0)\""
  echo "}"
} > "$OUT/build-manifest.json"

say "artifact      : $OUT/symoneural-web"
say "sha256        : $SHA"
say "build id      : $BUILD_ID"
say "manifest      : $OUT/build-manifest.json"
say "OK"
